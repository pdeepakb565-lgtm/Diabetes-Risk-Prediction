# Stage 11: Threshold Tuning

from sklearn.model_selection import train_test_split
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import Pipeline
from sklearn.base import clone

# Split training data into training and validation sets
X_fit, X_val, y_fit, y_val = train_test_split(
    X_train,
    y_train,
    test_size=0.25,
    random_state=42,
    stratify=y_train
)

# Store the three algorithms
algorithms = {
    "KNN": knn_model,
    "Logistic Regression": lr_model,
    "Decision Tree": dt_model
}

tuned_thresholds = {}

# Tune threshold for each model
for name, algorithm in algorithms.items():

    # Create preprocessing and model pipeline
    pipeline = Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
        ("model", clone(algorithm))
    ])

    # Train using training portion
    pipeline.fit(X_fit, y_fit)

    # Calculate validation probabilities
    probabilities = pipeline.predict_proba(X_val)[:, 1]

    # Set threshold for approximately top 30% risk
    threshold = np.percentile(probabilities, 70)

    tuned_thresholds[name] = threshold

    # Calculate selected patients
    predictions = (probabilities >= threshold).astype(int)

    selected_percentage = predictions.mean() * 100

    print("\nModel:", name)
    print("Tuned Threshold:", round(threshold, 4))
    print("Patients selected:", round(selected_percentage, 2), "%")

print("\nThreshold Tuning Completed Successfully!")

# Stage 12: Select Top 30% High-Risk Patients

for name, algorithm in algorithms.items():

    pipeline = Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
        ("model", clone(algorithm))
    ])

    pipeline.fit(X_fit, y_fit)

    probabilities = pipeline.predict_proba(X_val)[:, 1]

    # Calculate number of patients to select
    number_to_select = int(np.ceil(len(probabilities) * 0.30))

    # Select patients with the highest risk
    selected_indices = np.argsort(probabilities)[-number_to_select:]

    predictions = np.zeros(len(probabilities), dtype=int)
    predictions[selected_indices] = 1

    print("\nModel:", name)
    print("Total validation patients:", len(probabilities))
    print("High-risk patients selected:", predictions.sum())
    print("Selection percentage:",
          round(predictions.mean() * 100, 2), "%")

print("\nTop 30% Patient Selection Completed!")

# Stage 13: Evaluate Models Based on Top 30% Selection

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix
)

results = {}

for name, algorithm in algorithms.items():

    pipeline = Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
        ("model", clone(algorithm))
    ])

    pipeline.fit(X_fit, y_fit)

    probabilities = pipeline.predict_proba(X_val)[:, 1]

    # Select the top 30% highest-risk patients
    number_to_select = int(np.ceil(len(probabilities) * 0.30))
    selected_indices = np.argsort(probabilities)[-number_to_select:]

    predictions = np.zeros(len(probabilities), dtype=int)
    predictions[selected_indices] = 1

    # Evaluate model performance
    accuracy = accuracy_score(y_val, predictions)
    precision = precision_score(y_val, predictions, zero_division=0)
    recall = recall_score(y_val, predictions, zero_division=0)
    f1 = f1_score(y_val, predictions, zero_division=0)
    cm = confusion_matrix(y_val, predictions)

    results[name] = {
        "Accuracy": accuracy,
        "Precision": precision,
        "Recall": recall,
        "F1-Score": f1
    }

    print("\n==========", name, "==========")
    print("Accuracy:", round(accuracy, 4))
    print("Precision:", round(precision, 4))
    print("Recall:", round(recall, 4))
    print("F1-Score:", round(f1, 4))
    print("Confusion Matrix:")
    print(cm)

